class FaSound {
  final String ch; // 글자(홀로 모양)
  final String name; // 글자 이름(페르시아어)
  final String nameKo; // 이름 한글 읽기
  final String roman; // 로마자
  final String ipa;
  final String place; // 소리 나는 곳·입 모양
  final String korSim; // 비슷한 한국어 소리
  final String korDiff; // 한국어 화자가 주의할 점
  final String say; // TTS 로 읽힐 글(글자 이름 또는 예 낱말)
  final String example; // 예 낱말(페르시아어 = 뜻)
  final String group; // 묶음 칩
  const FaSound(this.ch, this.name, this.nameKo, this.roman, this.ipa, this.place, this.korSim, this.korDiff, this.say, this.example, this.group);
  bool get isVowel => group == 'vowel';
}

