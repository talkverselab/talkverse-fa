FaSound? faSoundOf(String ch) {
  for (final s in [...faLetters, ...faVowels]) {
    if (s.ch == ch) return s;
  }
  if (ch == 'ء') {
    return const FaSound('ء', 'همزه', '함제', "'", 'ʔ', '성대를 잠깐 닫았다 연다(성문 파열음).', '무음(끊김)', 'ع 와 같은 소리. 주로 다른 글자 위·사이에 작게 붙는다.', 'همزه', 'مسئله = 문제', 'same');
  }
  return null;
}
